-- Views behind the four specialist agents (508_specialist_agents.sql): Recovery Strategist, Pricing & Promo,
-- Forecast & Risk and Competitive benchmarking. Like every V_TOOL_* view they carry the row access policy
-- (sql/70_sec/702_row_access.sql) and read the replay-filtered source, so they move with AS_OF_WEEK_END.
USE ROLE SR_DEV;

-- Brand x market x period totals: L4W, L12W, L52W and the same weeks a year ago (_YA), ending at AS_OF_WEEK_END
CREATE OR REPLACE VIEW SR_DB.SEM.V_TOOL_BRAND_PERIOD
COMMENT = 'Brand totals per market and period (L4W, L12W, L52W and year-ago), with base sales, distribution and stores'
AS
WITH a AS (SELECT SETTING_VALUE::VARCHAR::DATE AS AS_OF FROM SR_DB.OPS.SETTINGS WHERE SETTING_KEY = 'AS_OF_WEEK_END'),
p AS (
  SELECT column1 AS PERIOD_CODE, column2 AS WEEKS, column3 AS LAG_WEEKS
  FROM VALUES ('L4W', 4, 0), ('L12W', 12, 0), ('L52W', 52, 0), ('L4W_YA', 4, 52), ('L12W_YA', 12, 52), ('L52W_YA', 52, 52)
)
SELECT p.PERIOD_CODE, a.AS_OF AS AS_OF_WEEK, f.MARKET_ID, m.MARKET_NAME, m.MARKET_LEVEL, m.REGION, m.CITY,
       pr.CATEGORY, pr.MANUFACTURER, pr.BRAND,
       SUM(f.VALUE_SALES) AS VALUE_SALES, SUM(f.UNIT_SALES) AS UNIT_SALES,
       SUM(f.BASE_VALUE_SALES) AS BASE_VALUE_SALES, AVG(f.ACV_DIST_PCT) AS ACV_DIST_PCT,
       SUM(f.STORES_SELLING) AS STORE_WEEKS, COUNT(DISTINCT IFF(f.VALUE_SALES > 0, f.PRODUCT_ID, NULL)) AS SKUS
FROM SR_DB.SRC.V_SRC_FACT_WEEKLY f
JOIN SR_DB.SRC.V_SRC_PRODUCT pr ON pr.PRODUCT_ID = f.PRODUCT_ID
JOIN SR_DB.SRC.V_SRC_MARKET m ON m.MARKET_ID = f.MARKET_ID
CROSS JOIN a
JOIN p ON f.WEEK_END_DATE >  DATEADD(week, -(p.WEEKS + p.LAG_WEEKS), a.AS_OF)
      AND f.WEEK_END_DATE <= DATEADD(week, -p.LAG_WEEKS, a.AS_OF)
GROUP BY p.PERIOD_CODE, a.AS_OF, f.MARKET_ID, m.MARKET_NAME, m.MARKET_LEVEL, m.REGION, m.CITY,
         pr.CATEGORY, pr.MANUFACTURER, pr.BRAND;

-- Pricing & Promo: per brand, market and period, with the year-ago period alongside
CREATE OR REPLACE VIEW SR_DB.SEM.V_TOOL_PRICE_PROMO
COMMENT = 'Price per unit, price index vs category, promo share of sales and promo lift, now and a year ago'
AS
WITH b AS (
  SELECT x.*, SUM(VALUE_SALES) OVER (PARTITION BY PERIOD_CODE, MARKET_ID, CATEGORY) AS CAT_VALUE,
         SUM(UNIT_SALES)  OVER (PARTITION BY PERIOD_CODE, MARKET_ID, CATEGORY) AS CAT_UNITS
  FROM SR_DB.SEM.V_TOOL_BRAND_PERIOD x
), m AS (
  SELECT PERIOD_CODE, AS_OF_WEEK, MARKET_ID, MARKET_NAME, MARKET_LEVEL, REGION, CITY, CATEGORY, MANUFACTURER, BRAND,
         VALUE_SALES, UNIT_SALES,
         VALUE_SALES / NULLIF(UNIT_SALES, 0)                                   AS PRICE_PER_UNIT,
         (VALUE_SALES / NULLIF(UNIT_SALES, 0)) / NULLIF(CAT_VALUE / NULLIF(CAT_UNITS, 0), 0) AS PRICE_INDEX,
         (VALUE_SALES - BASE_VALUE_SALES) / NULLIF(VALUE_SALES, 0)              AS PROMO_SHARE,
         VALUE_SALES / NULLIF(BASE_VALUE_SALES, 0) - 1                          AS PROMO_LIFT,
         VALUE_SALES / NULLIF(CAT_VALUE, 0)                                     AS VALUE_SHARE
  FROM b
)
SELECT n.PERIOD_CODE, n.AS_OF_WEEK, n.MARKET_ID, n.MARKET_NAME, n.MARKET_LEVEL, n.REGION, n.CITY, n.CATEGORY,
       n.MANUFACTURER, n.BRAND, n.VALUE_SALES, n.VALUE_SHARE, n.PRICE_PER_UNIT, n.PRICE_INDEX, n.PROMO_SHARE, n.PROMO_LIFT,
       y.PRICE_PER_UNIT AS PRICE_PER_UNIT_YA, y.PRICE_INDEX AS PRICE_INDEX_YA, y.PROMO_SHARE AS PROMO_SHARE_YA,
       n.PRICE_PER_UNIT / NULLIF(y.PRICE_PER_UNIT, 0) - 1 AS PRICE_CHG_YA,
       n.VALUE_SHARE - y.VALUE_SHARE                       AS SHARE_CHG_YA
FROM m n
LEFT JOIN m y ON y.PERIOD_CODE = n.PERIOD_CODE || '_YA' AND y.MARKET_ID = n.MARKET_ID AND y.CATEGORY = n.CATEGORY
             AND y.BRAND = n.BRAND AND y.MANUFACTURER = n.MANUFACTURER
WHERE n.PERIOD_CODE IN ('L4W', 'L12W', 'L52W');

-- Competitive benchmarking: per manufacturer, market and period, ranked, with the year-ago period alongside
CREATE OR REPLACE VIEW SR_DB.SEM.V_TOOL_BENCHMARK
COMMENT = 'Manufacturer value share, rank, distribution, velocity, price index and SKUs per market and period, vs year ago'
AS
WITH g AS (
  SELECT PERIOD_CODE, AS_OF_WEEK, MARKET_ID, MARKET_NAME, MARKET_LEVEL, REGION, CITY, CATEGORY, MANUFACTURER,
         SUM(VALUE_SALES) AS VALUE_SALES, SUM(UNIT_SALES) AS UNIT_SALES, AVG(ACV_DIST_PCT) AS ACV_DIST_PCT,
         SUM(STORE_WEEKS) AS STORE_WEEKS, SUM(SKUS) AS SKUS, COUNT(DISTINCT BRAND) AS BRANDS
  FROM SR_DB.SEM.V_TOOL_BRAND_PERIOD
  GROUP BY PERIOD_CODE, AS_OF_WEEK, MARKET_ID, MARKET_NAME, MARKET_LEVEL, REGION, CITY, CATEGORY, MANUFACTURER
), m AS (
  SELECT g.*,
         VALUE_SALES / NULLIF(SUM(VALUE_SALES) OVER (PARTITION BY PERIOD_CODE, MARKET_ID, CATEGORY), 0) AS VALUE_SHARE,
         RANK() OVER (PARTITION BY PERIOD_CODE, MARKET_ID, CATEGORY ORDER BY VALUE_SALES DESC)        AS SHARE_RANK,
         UNIT_SALES / NULLIF(STORE_WEEKS, 0)                                                          AS VELOCITY,
         (VALUE_SALES / NULLIF(UNIT_SALES, 0))
           / NULLIF(SUM(VALUE_SALES) OVER (PARTITION BY PERIOD_CODE, MARKET_ID, CATEGORY)
                    / NULLIF(SUM(UNIT_SALES) OVER (PARTITION BY PERIOD_CODE, MARKET_ID, CATEGORY), 0), 0) AS PRICE_INDEX
  FROM g
)
SELECT n.PERIOD_CODE, n.AS_OF_WEEK, n.MARKET_ID, n.MARKET_NAME, n.MARKET_LEVEL, n.REGION, n.CITY, n.CATEGORY,
       n.MANUFACTURER, n.BRANDS, n.SKUS, n.VALUE_SALES, n.VALUE_SHARE, n.SHARE_RANK, n.ACV_DIST_PCT, n.VELOCITY,
       n.PRICE_INDEX, y.VALUE_SHARE AS VALUE_SHARE_YA, y.SHARE_RANK AS SHARE_RANK_YA,
       n.VALUE_SHARE - y.VALUE_SHARE AS SHARE_CHG_YA, n.ACV_DIST_PCT - y.ACV_DIST_PCT AS ACV_CHG_YA,
       n.VALUE_SALES / NULLIF(y.VALUE_SALES, 0) - 1 AS SALES_GROWTH_YA
FROM m n
LEFT JOIN m y ON y.PERIOD_CODE = n.PERIOD_CODE || '_YA' AND y.MARKET_ID = n.MARKET_ID AND y.CATEGORY = n.CATEGORY
             AND y.MANUFACTURER = n.MANUFACTURER
WHERE n.PERIOD_CODE IN ('L4W', 'L12W', 'L52W');

-- Forecast & Risk: the latest successful run's early-warning signals with market names
CREATE OR REPLACE VIEW SR_DB.SEM.V_TOOL_EARLY_WARNING
COMMENT = 'Early-warning signals (distribution drop, price rise) of the latest successful run with projected share effect'
AS
SELECT e.RUN_ID, e.MARKET_ID, m.MARKET_NAME, m.MARKET_LEVEL, m.REGION, m.CITY, e.CATEGORY, e.BRAND, e.SIGNAL,
       e.LATEST_WEEK, e.LEVER_LATEST, e.LEVER_L4W, e.LEVER_CHG, e.PROJECTED_SHARE_PTS, e.ML_CONFIRMED, e.NOTE
FROM SR_DB.APP.EARLY_WARNING e
JOIN SR_DB.SRC.V_SRC_MARKET m ON m.MARKET_ID = e.MARKET_ID
WHERE e.RUN_ID = (SELECT RUN_ID FROM SR_DB.OPS.RUN_LOG WHERE STATUS = 'SUCCEEDED' ORDER BY STARTED_AT DESC LIMIT 1);
